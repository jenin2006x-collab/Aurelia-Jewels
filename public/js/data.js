  getProductsByCategory: function(cat) {
    if (!cat) return this.products;
    const c = String(cat).trim().toLowerCase();

    // Specific subcategory requests
    if (c === "cross chain" || c === "cross chains") {
      return this.products.filter(function(p) {
        return p.category === "Chains" && ((p.subcategory || "").toLowerCase().includes("cross") || p.name.toLowerCase().includes("cross"));
      });
    }
    if (c === "hug ring" || c === "hug rings") {
      return this.products.filter(function(p) {
        return p.category === "Rings" && ((p.subcategory || "").toLowerCase().includes("hug") || p.name.toLowerCase().includes("hug"));
      });
    }

    return this.products.filter(function(p) {
      const pc = p.category.toLowerCase();
      if (pc === c) return true;
      if ((c === "necklace" || c === "necklaces") && pc === "necklaces") return true;
      if ((c === "necklace set" || c === "necklace sets") && pc === "necklace sets") return true;
      if ((c === "chain" || c === "chains") && pc === "chains") return true;
      if ((c === "pendant" || c === "pendants") && pc === "pendants") return true;
      if ((c === "earring" || c === "earrings") && pc === "earrings") return true;
      if ((c === "ring" || c === "rings") && pc === "rings") return true;
      if ((c === "bangle" || c === "bangles") && pc === "bangles") return true;
      if ((c === "bracelet" || c === "bracelets") && pc === "bracelets") return true;
      return false;
    });
  },

  getRelatedProducts: function(product) {
    if (!product) return [];
    const cat = product.category;
    let targetCats = [cat];
    if (cat === "Necklaces") targetCats = ["Necklaces", "Necklace Sets", "Pendants"];
    else if (cat === "Necklace Sets") targetCats = ["Necklace Sets", "Necklaces", "Earrings"];
    else if (cat === "Chains") targetCats = ["Chains", "Pendants", "Necklaces"];
    else if (cat === "Pendants") targetCats = ["Pendants", "Chains", "Necklaces"];
    else if (cat === "Earrings") targetCats = ["Earrings", "Necklace Sets"];
    else if (cat === "Rings") targetCats = ["Rings", "Bracelets"];
    else if (cat === "Bangles") targetCats = ["Bangles", "Bracelets"];
    else if (cat === "Bracelets") targetCats = ["Bracelets", "Bangles", "Rings"];
    return this.products.filter(function(p) {
      return p.id !== product.id && targetCats.includes(p.category);
    }).slice(0, 4);
  },

  search: function(query) {
    if (!query) return this.products;
    const q = String(query).trim().toLowerCase();
    // Mangalsutra completely removed - must return zero results
    if (q === "mangalsutra" || q === "mangalsutras") return [];

    // "cross chain" search specifically surfaces cross chain items within Chains
    if (q === "cross chain" || q === "cross chains") {
      return this.products.filter(function(p) {
        return p.category === "Chains" && ((p.subcategory || "").toLowerCase().includes("cross") || p.name.toLowerCase().includes("cross"));
      });
    }

    // "hug ring" search specifically surfaces hug ring items within Rings
    if (q === "hug ring" || q === "hug rings") {
      return this.products.filter(function(p) {
        return p.category === "Rings" && ((p.subcategory || "").toLowerCase().includes("hug") || p.name.toLowerCase().includes("hug"));
      });
    }

    // "chain" search returns all Chains (including cross chain designs)
    if (q === "chain" || q === "chains") {
      return this.products.filter(function(p) {
        return p.category === "Chains" || p.name.toLowerCase().includes("chain");
      });
    }

    // "ring" search returns all Rings (including hug ring designs)
    if (q === "ring" || q === "rings") {
      return this.products.filter(function(p) {
        return p.category === "Rings" || p.name.toLowerCase().includes("ring");
      });
    }

    // "necklace" search returns Necklaces and Necklace Sets
    if (q === "necklace" || q === "necklaces") {
      return this.products.filter(function(p) {
        return p.category === "Necklaces" || p.category === "Necklace Sets" || p.name.toLowerCase().includes("necklace");
      });
    }

    return this.products.filter(function(p) {
      const matchName = p.name.toLowerCase().includes(q);
      const matchCat = p.category.toLowerCase().includes(q);
      const matchSub = (p.subcategory || "").toLowerCase().includes(q);
      const matchMetal = p.metal.toLowerCase().includes(q);
      const matchStone = (p.stone || "").toLowerCase().includes(q);
      const matchDesc = (p.desc || p.description || "").toLowerCase().includes(q);
      const matchPolish = (p.polish || "").toLowerCase().includes(q);
      return matchName || matchCat || matchSub || matchMetal || matchStone || matchDesc || matchPolish;
    });
  },

