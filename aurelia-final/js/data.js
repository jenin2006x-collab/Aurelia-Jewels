    let targetCats = [cat];
    if (cat === 'Necklaces') targetCats = ['Necklaces', 'Necklace Sets', 'Chains', 'Pendants'];
    else if (cat === 'Necklace Sets') targetCats = ['Necklace Sets', 'Necklaces', 'Earrings'];
    else if (cat === 'Chains') targetCats = ['Chains', 'Cross Chains', 'Pendants'];
    else if (cat === 'Cross Chains') targetCats = ['Cross Chains', 'Chains', 'Pendants'];
    else if (cat === 'Pendants') targetCats = ['Pendants', 'Chains', 'Necklaces'];
    else if (cat === 'Earrings') targetCats = ['Earrings', 'Necklace Sets'];
    else if (cat === 'Rings') targetCats = ['Rings', 'Hug Rings'];
    else if (cat === 'Hug Rings') targetCats = ['Hug Rings', 'Rings'];
